"""Prompt-level sensitivity experiment runner (#133): VS or SSoT.

Production-equivalent runner for the new VS / SSoT cells in the
prompt-sensitivity experiment. Re-uses the parallel generation
orchestration and embedding pipeline from ``scripts/run_diversity_experiment.py``
and only swaps in:

- the prompt template (``prompts/vs.md`` for VS, ``prompts/ssot.md`` for SSoT)
- the structured-output schema (``StructuredVSOutput`` for VS,
  ``StructuredSSoTOutput`` for SSoT)
- the per-call → per-sample expansion: a VS call returns ``k=3`` ideas, so 30
  per-cell samples are produced from 10 calls, with sample_index encoding
  ``batch_idx*3 + within_batch_idx``. SSoT is 1 call → 1 sample (matching
  existing phase2).

The default-prompt cells are NOT regenerated by this runner — they are
read from the existing ``phase2_*`` directories at evaluation time, with the
per-model Q1/Q4 keyword subset filter applied.

Single-cell run (one model × one effort × one prompt-method × one keyword
subset). Output dir layout matches ``phase2_*`` so the existing evaluation
pipeline (paper_stats.py, embedding_structure.py, judge scripts) re-runs
unchanged.

Usage:
    uv run python scripts/experiment/prompt_sensitivity/run_prompt_sensitivity.py \\
        --model claude \\
        --prompt vs \\
        --effort low \\
        --kw-subset results/effort_diversity/prompt_sensitivity/q1_q4_claude.csv \\
        --samples-per-effort 30 \\
        --output-dir results/effort_diversity/prompt_sensitivity_pilot/claude_vs_low \\
        --max-concurrency 30
"""

