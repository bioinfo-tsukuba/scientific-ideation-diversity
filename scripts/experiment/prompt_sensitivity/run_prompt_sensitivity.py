# ---- Per-call generation (reused for all 3 methods) ---------------------


def _build_configs() -> tuple[BedrockConfig, VertexAIConfig, GoogleAIStudioConfig]:
    bedrock_region_str = (
        os.getenv("BEDROCK_REGION")
        or os.getenv("AWS_REGION")
        or os.getenv("AWS_DEFAULT_REGION")
        or AwsRegion.AP_NORTHEAST_1.value
    )
    bedrock_cfg = BedrockConfig(region=AwsRegion(bedrock_region_str))
    vertex_ai_cfg = VertexAIConfig(
        project=os.getenv("VERTEX_AI_PROJECT", ""),
        location=os.getenv("VERTEX_AI_LOCATION", "global"),
    )
    google_ai_studio_cfg = GoogleAIStudioConfig()
    return bedrock_cfg, vertex_ai_cfg, google_ai_studio_cfg


def generate_one_batch(
    *,
    keyword: str,
    category: Optional[str],
    idea_model: IdeaModelName,
    provider: GenerationProviderName,
    effort: EffortName,
    batch_index: int,
    prompt_method: str,
    idea_prompt_template: str,
    schema: type[StructuredOutput],
    embedding_model: str,
    bedrock_cfg: BedrockConfig,
    vertex_ai_cfg: VertexAIConfig,
    google_ai_studio_cfg: GoogleAIStudioConfig,
) -> list[SampleRecord]:
    """One LLM call → list of SampleRecord (1 for default/SSoT, 3 for VS)."""
    idea_prompt = idea_prompt_template.replace("{{keywords}}", keyword)
    error_base = {
        "keyword": keyword,
        "category": category,
        "prompt_style": prompt_method,
        "effort": effort.value,
        "batch_index": batch_index,
        "idea_model": idea_model.value,
        "embedding_model": embedding_model,
    }
    try:
        generation = generate_idea(
            idea_prompt,
            idea_model=idea_model,
            provider=provider,
            effort=effort,
            structured_output_schema=schema,
            bedrock_config=bedrock_cfg,
            vertex_ai_config=vertex_ai_cfg,
            google_ai_studio_config=google_ai_studio_cfg,
        )
    except Exception as exc:
        raise SampleGenerationError(
            {
                **error_base,
                "error_type": type(exc).__name__,
                "error_message": str(exc),
                "timestamp": datetime.now().isoformat(),
            }
        ) from exc

    so = generation.structured_output
    common_kwargs = dict(
        keyword=keyword,
        category=category,
        prompt_style=PROMPT_METHOD_TO_STYLE[prompt_method].value,
        effort=effort.value,
        idea_model=idea_model.value,
        embedding_model=embedding_model,
        full_response=generation.text,
        pydantic_validation_status=PydanticValidationStatus.PASSED,
        pydantic_validation_error=None,
        response_reasoning=clean_text(generation.response_reasoning) if generation.response_reasoning else None,
        has_reasoning_block=generation.has_reasoning_block,
        stop_reason=generation.stop_reason,
        input_tokens=generation.input_tokens,
        output_tokens=generation.output_tokens,
        total_tokens=generation.total_tokens,
        raw_api_response=generation.raw_api_response,
        api_calls=generation.api_calls,
        embedding_input_tokens=0,
        timestamp=datetime.now().isoformat(),
    )

    if isinstance(so, StructuredVSOutput):
        records: list[SampleRecord] = []
        for within_idx, item in enumerate(so.responses):
            sample_idx = batch_index * 3 + within_idx
            idea_text = clean_text(item.combined_text())
            records.append(
                SampleRecord(
                    sample_index=sample_idx,
                    idea=idea_text,
                    structured_output=item,
                    word_count=len(idea_text.split()),
                    char_count=len(idea_text),
                    **common_kwargs,
                )
            )
        return records

    # default / SSoT: 1 call → 1 record
    idea_text = clean_text(so.combined_text())
    return [
        SampleRecord(
            sample_index=batch_index,
            idea=idea_text,
            structured_output=so,
            word_count=len(idea_text.split()),
            char_count=len(idea_text),
            **common_kwargs,
        )
    ]


# ---- Orchestration -------------------------------------------------------


def build_batch_tasks(
    *,
    keyword_rows: list[dict[str, Optional[str]]],
    effort: str,
    n_batches: int,
) -> list[tuple[str, Optional[str], str, int]]:
    """Per-(kw, batch_index) tasks; effort is fixed for the run."""
    return [
        (keyword_row["keyword"], keyword_row.get("category"), effort, batch_index)
        for batch_index in range(n_batches)
        for keyword_row in keyword_rows
    ]


def infer_missing_batch_tasks(
    *,
    existing_records: list[SampleRecord],
    keyword_rows: list[dict[str, Optional[str]]],
    effort: EffortName,
    n_batches: int,
    prompt_method: str,
) -> list[tuple[str, Optional[str], str, int]]:
    """Compute (kw, category, effort, batch_index) tasks not yet completed.

    A batch is "completed" iff samples.jsonl has at least one record for that
    (keyword, batch_index) under the matching effort+prompt_style. Because a VS
    call returns k=3 ideas atomically, partial completion within a batch is
    impossible, so any record for batch_idx implies all k samples were saved.
    """
    k = PROMPT_METHOD_K[prompt_method]
    expected_style = PROMPT_METHOD_TO_STYLE[prompt_method]
    completed: dict[str, set[int]] = {}
    for r in existing_records:
        if r.effort != effort or r.prompt_style != expected_style:
            continue
        completed.setdefault(r.keyword, set()).add(r.sample_index // k)
    missing: list[tuple[str, Optional[str], str, int]] = []
    for row in keyword_rows:
        kw = row["keyword"]
        cat = row.get("category")
        for bi in range(n_batches):
            if bi not in completed.get(kw, set()):
                missing.append((kw, cat, effort.value, bi))
    return missing


def run_generation(
    *,
    keyword_rows: list[dict[str, Optional[str]]],
    idea_model: IdeaModelName,
    provider: GenerationProviderName,
    effort: EffortName,
    samples_per_effort: int,
    prompt_method: str,
    output_dir: Path,
    embedding_model: str,
    max_concurrency: int,
    tasks: Optional[list[tuple[str, Optional[str], str, int]]] = None,
    success_log_filename: str = "samples.jsonl",
) -> list[SampleRecord]:
    schema = PROMPT_METHOD_TO_SCHEMA[prompt_method]
    k = PROMPT_METHOD_K[prompt_method]
    if samples_per_effort % k != 0:
        raise ValueError(
            f"samples_per_effort ({samples_per_effort}) is not divisible by k={k} for prompt_method={prompt_method!r}"
        )
    n_batches = samples_per_effort // k

    idea_prompt_template = load_prompt_template(prompt_method)
    bedrock_cfg, vertex_ai_cfg, google_ai_studio_cfg = _build_configs()

    samples_jsonl = output_dir / success_log_filename
    errors_jsonl = output_dir / "errors.jsonl"
    output_dir.mkdir(parents=True, exist_ok=True)

    if tasks is None:
        tasks = build_batch_tasks(
            keyword_rows=keyword_rows,
            effort=effort.value,
            n_batches=n_batches,
        )
    if not tasks:
        return []
    logger.info(
        "[%s/%s/%s] %d kw × %d batches = %d tasks (k=%d → %d samples/cell)",
        idea_model.value,
        prompt_method,
        effort.value,
        len(keyword_rows),
        n_batches,
        len(tasks),
        k,
        samples_per_effort,
    )

    records: list[SampleRecord] = []
    append_lock = threading.Lock()
    max_workers = max(1, min(max_concurrency, len(tasks)))

    def submit(
        executor: concurrent.futures.ThreadPoolExecutor,
        task: tuple[str, Optional[str], str, int],
    ) -> concurrent.futures.Future[list[SampleRecord]]:
        keyword, category, effort_str, batch_idx = task
        return executor.submit(
            generate_one_batch,
            keyword=keyword,
            category=category,
            idea_model=idea_model,
            provider=provider,
            effort=EffortName(effort_str),
            batch_index=batch_idx,
            prompt_method=prompt_method,
            idea_prompt_template=idea_prompt_template,
            schema=schema,
            embedding_model=embedding_model,
            bedrock_cfg=bedrock_cfg,
            vertex_ai_cfg=vertex_ai_cfg,
            google_ai_studio_cfg=google_ai_studio_cfg,
        )

    task_iter = iter(tasks)
    with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as ex:
        future_to_task: dict[concurrent.futures.Future, tuple] = {}
        for _ in range(max_workers):
            try:
                future_to_task[submit(ex, next(task_iter))] = "primed"
            except StopIteration:
                break
        completed = 0
        while future_to_task:
            done, _ = concurrent.futures.wait(future_to_task, return_when=concurrent.futures.FIRST_COMPLETED)
            for fut in done:
                future_to_task.pop(fut)
                completed += 1
                try:
                    new_records = fut.result()
                    records.extend(new_records)
                    with append_lock:
                        for r in new_records:
                            append_jsonl(samples_jsonl, r.model_dump(mode="json"))
                except SampleGenerationError as exc:
                    with append_lock:
                        append_jsonl(errors_jsonl, exc.payload)
                if completed % 10 == 0 or completed == len(tasks):
                    print(
                        f"[generate] {completed}/{len(tasks)} batches done",
                        flush=True,
                    )
                try:
                    future_to_task[submit(ex, next(task_iter))] = "primed"
                except StopIteration:
                    continue
    return sort_sample_records(records)


# ---- CLI entrypoint ------------------------------------------------------


def load_keyword_rows(csv_path: Path) -> list[dict[str, Optional[str]]]:
    rows: list[dict[str, Optional[str]]] = []
    with csv_path.open() as f:
        for row in csv.DictReader(f):
            rows.append(
                {
                    "keyword": row["keyword"],
                    "category": row.get("category"),
                    "stratum": row.get("stratum"),
                }
            )
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--model", required=True, choices=list(MODEL_TO_PROVIDER.keys()))
    parser.add_argument("--prompt", required=True, choices=list(PROMPT_METHOD_TO_SCHEMA.keys()))
    parser.add_argument("--effort", required=True, choices=["low", "medium", "high"])
    parser.add_argument(
        "--kw-subset",
        type=Path,
        required=True,
        help="CSV with at least 'keyword' and 'category' columns.",
    )
    parser.add_argument(
        "--samples-per-effort",
        type=int,
        default=30,
        help="Samples per (kw, effort) cell (must be divisible by k=3 for VS).",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help=(
            "Cell-level output directory for a fresh run. Required unless "
            "--resume-output-dir or --resume-generation-output-dir is given."
        ),
    )
    parser.add_argument(
        "--resume-output-dir",
        type=Path,
        default=None,
        help=(
            "Resume from an existing run directory containing samples.jsonl: "
            "skip generation entirely and rerun only embedding/aggregation."
        ),
    )
    parser.add_argument(
        "--resume-generation-output-dir",
        type=Path,
        default=None,
        help=(
            "Resume generation into an existing run directory by backfilling "
            "only missing (keyword, batch_index) tasks; new records go to "
            "backfill_successes.jsonl. Then continues to embedding (unless "
            "--skip-embedding)."
        ),
    )
    parser.add_argument(
        "--embedding-models",
        nargs="+",
        default=["text-embedding-3-large"],
        help="Embedding models to compute (re-uses production embedding pipeline).",
    )
    parser.add_argument("--max-concurrency", type=int, default=30)
    parser.add_argument("--specter2-batch-size", type=int, default=8)
    parser.add_argument(
        "--skip-embedding",
        action="store_true",
        help="Skip embedding step (useful for pilot inspection).",
    )
    args = parser.parse_args()
    resume_modes = sum(1 for x in (args.resume_output_dir, args.resume_generation_output_dir) if x)
    if resume_modes > 1:
        parser.error("Specify at most one of --resume-output-dir and --resume-generation-output-dir.")
    if args.output_dir is None and resume_modes == 0:
        parser.error("--output-dir is required for a fresh run (or pass one of the --resume-*-output-dir flags).")

    idea_model, provider = MODEL_TO_PROVIDER[args.model]
    effort = EffortName(args.effort)

    keyword_rows = load_keyword_rows(args.kw_subset)
    if not keyword_rows:
        raise ValueError(f"no keywords in {args.kw_subset}")

    # Three modes (mirrors scripts/run_diversity_experiment.py main()):
    #   1. --resume-generation-output-dir <dir>: backfill missing batches
    #   2. --resume-output-dir <dir>: skip generation entirely, just rerun embedding
    #   3. (default): fresh run into --output-dir
    if args.resume_generation_output_dir is not None:
        output_dir = args.resume_generation_output_dir
        samples_path = output_dir / "samples.jsonl"
        if not samples_path.exists():
            raise FileNotFoundError(f"Missing samples.jsonl in resume directory: {output_dir}")
        existing_records = load_sample_records(samples_path)
        # Also fold in any previous backfill_successes.jsonl so a 2nd resume run
        # does not re-issue batches the 1st backfill already recovered. Dedupe
        # by sample-task key in case earlier (pre-fix) runs appended duplicates.
        backfill_path = output_dir / "backfill_successes.jsonl"
        if backfill_path.exists():
            existing_records = sort_sample_records(existing_records + load_sample_records(backfill_path))
            seen: set[tuple] = set()
            deduped: list[SampleRecord] = []
            for r in existing_records:
                key = (r.keyword, r.prompt_style, r.effort, r.sample_index)
                if key in seen:
                    continue
                seen.add(key)
                deduped.append(r)
            existing_records = deduped
        k = PROMPT_METHOD_K[args.prompt]
        n_batches = args.samples_per_effort // k
        missing = infer_missing_batch_tasks(
            existing_records=existing_records,
            keyword_rows=keyword_rows,
            effort=effort,
            n_batches=n_batches,
            prompt_method=args.prompt,
        )
        print(
            f"[resume-generate] existing_successes={len(existing_records)} missing_tasks={len(missing)}",
            flush=True,
        )
        backfill = run_generation(
            keyword_rows=keyword_rows,
            idea_model=idea_model,
            provider=provider,
            effort=effort,
            samples_per_effort=args.samples_per_effort,
            prompt_method=args.prompt,
            output_dir=output_dir,
            embedding_model=args.embedding_models[0],
            max_concurrency=args.max_concurrency,
            tasks=missing,
            success_log_filename="backfill_successes.jsonl",
        )
        records = sort_sample_records(existing_records + backfill)
        logger.info(
            "resume-generate: existing=%d backfill=%d total=%d",
            len(existing_records),
            len(backfill),
            len(records),
        )
    elif args.resume_output_dir is not None:
        output_dir = args.resume_output_dir
        samples_path = output_dir / "samples.jsonl"
        if not samples_path.exists():
            raise FileNotFoundError(f"Missing samples.jsonl in resume directory: {output_dir}")
        records = load_sample_records(samples_path)
        # Fold in any backfill_successes.jsonl produced by prior --resume-
        # generation-output-dir runs (prod's --resume-output-dir matches this:
        # see materialize_generation_artifacts copying both files into the
        # per-embedding subdir). Dedupe by sample-task key.
        backfill_path = output_dir / "backfill_successes.jsonl"
        if backfill_path.exists():
            records = sort_sample_records(records + load_sample_records(backfill_path))
            seen2: set[tuple] = set()
            deduped2: list[SampleRecord] = []
            for r in records:
                key = (r.keyword, r.prompt_style, r.effort, r.sample_index)
                if key in seen2:
                    continue
                seen2.add(key)
                deduped2.append(r)
            records = deduped2
        logger.info("resume-output-dir: loaded %d records (embedding only)", len(records))
    else:
        output_dir = args.output_dir
        records = run_generation(
            keyword_rows=keyword_rows,
            idea_model=idea_model,
            provider=provider,
            effort=effort,
            samples_per_effort=args.samples_per_effort,
            prompt_method=args.prompt,
            output_dir=output_dir,
            embedding_model=args.embedding_models[0],
            max_concurrency=args.max_concurrency,
        )
        logger.info("generated %d sample records", len(records))

    if args.skip_embedding:
        logger.info("--skip-embedding set; skipping embedding stage")
        return 0

    # Embedding (production-equivalent: combined + per-component + summary CSVs)
    embedding_models = [EmbeddingModelName(m) for m in args.embedding_models]
    specs = build_embedding_run_specs(
        base_output_dir=output_dir,
        embed_models=embedding_models,
    )
    schema = PROMPT_METHOD_TO_SCHEMA[args.prompt]
    for spec in specs:
        spec.output_dir.mkdir(parents=True, exist_ok=True)
        backend = _create_embed_backend(spec, args.specter2_batch_size)

        records_for_run = [r.for_embedding_model(spec.embedding_model) for r in records]
        # Copy generation artifacts (samples.jsonl + errors.jsonl) into the
        # embedding subdir so per-embedding evaluation has its own snapshot.
        materialize_generation_artifacts(
            source_dir=output_dir,
            target_dir=spec.output_dir,
            records=records_for_run,
        )
        write_sample_records(spec.output_dir / "samples.jsonl", records_for_run)

        embeddings = embed_records(
            records=records_for_run,
            spec=spec,
            embed_max_concurrency=args.max_concurrency,
            backend=backend,
        )
        # Re-write samples.jsonl after embedding (matches production behavior:
        # embed_records may update fields on the records).
        write_sample_records(spec.output_dir / "samples.jsonl", records_for_run)

        # Per-component (purpose / mechanism / evaluation) embeddings.
        # The per-record ``structured_output`` shape differs by method:
        #   ssot -> StructuredSSoTOutput (random_string + 3 facet fields)
        #   vs   -> FacetIdeaWithProbability (3 facet fields + probability)
        # We embed only the 3 facet text fields; probability and
        # random_string are non-text / numeric and are not embedded.
        record_schema: type[StructuredOutput] = FacetIdeaWithProbability if args.prompt == "vs" else schema
        component_fields = [f for f in record_schema.model_fields if f in {"purpose", "mechanism", "evaluation"}]
        for component in component_fields:
            try:
                texts = extract_record_texts(records_for_run, component)
            except Exception as exc:  # noqa: BLE001
                logger.warning("skipping per-component embedding for %s: %s", component, exc)
                continue
            embed_field(
                texts=texts,
                records=records_for_run,
                backend=backend,
                spec=spec,
                component=component,
                embed_max_concurrency=args.max_concurrency,
            )

        # Summary CSVs (consumed by paper_stats.py / quality_filtered_diversity
        # / embedding_structure pipelines).
        keyword_effort_rows = build_summary_by_keyword_effort_rows(records_for_run, embeddings)
        write_csv(spec.output_dir / "summary_by_keyword_effort.csv", keyword_effort_rows)

        effort_summary_rows = build_summary_by_effort_rows(keyword_effort_rows)
        write_csv(spec.output_dir / "summary.csv", effort_summary_rows)

        category_summary_rows = build_category_summary_rows(keyword_effort_rows)
        write_csv(spec.output_dir / "summary_by_category_effort.csv", category_summary_rows)

        centroid_header, centroid_rows = build_centroid_distance_rows(records_for_run, embeddings)
        write_matrix_csv(
            spec.output_dir / "centroid_distances.csv",
            centroid_header,
            centroid_rows,
        )

        coords, _ = pca_2d(embeddings)
        save_pca_coordinates(
            path=spec.output_dir / "pca_coordinates.csv",
            records=records_for_run,
            coords=coords,
        )

        logger.info(
            "[embed/%s] %d records, %d combined embeddings, %d component embeddings",
            spec.embedding_model.value,
            len(records_for_run),
            len(embeddings),
            len(component_fields),
        )

    return 0


