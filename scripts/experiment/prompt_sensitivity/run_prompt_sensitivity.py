# ---- Prompt + schema selection -------------------------------------------


PROMPT_METHOD_TO_SCHEMA: dict[str, type[StructuredOutput]] = {
    "vs": StructuredVSOutput,
    "ssot": StructuredSSoTOutput,
}

PROMPT_METHOD_TO_STYLE: dict[str, PromptStyleName] = {
    "vs": PromptStyleName.STRUCTURED_VS,
    "ssot": PromptStyleName.STRUCTURED_SSOT,
}

# Calls per cell when ``samples_per_effort = N``:
#   ssot -> N calls (1 call -> 1 idea)
#   vs   -> N // 3 calls (1 call -> 3 ideas)
PROMPT_METHOD_K: dict[str, int] = {"vs": 3, "ssot": 1}


def load_prompt_template(prompt_method: str) -> str:
    """Read the prompt template for the chosen method."""
    if prompt_method == "vs":
        return (REPO_ROOT / "prompts" / "vs.md").read_text()
    if prompt_method == "ssot":
        return (REPO_ROOT / "prompts" / "ssot.md").read_text()
    raise ValueError(f"Unknown prompt_method: {prompt_method!r}")


